    # dmu: 对均值mu的梯度 (D,)
    dmu = np.sum(dx_norm * (-std_inv), axis=0) + dvar * np.sum(-2.0 * x_minus_mu, axis=0) / N

    # 最终dx由三部分合并：来自dx_norm、来自dvar、来自dmu
    dx = dx_norm * std_inv + dvar * (2.0 * x_minus_mu / N) + dmu / N

    ###########################################################################
    #                             END OF YOUR CODE                            #
    ###########################################################################

    return dx, dgamma, dbeta


